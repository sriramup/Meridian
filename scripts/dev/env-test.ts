import fs from "node:fs";
import { loadWorld } from "./load";
import { prepareLandcover, buildLandcover, coverStats } from "@/sim/landcover";
import { runHeat, dqT } from "@/sim/heat";
import { runRunoff, runFlood } from "@/sim/environment";
import { prepareAccess, runAccess } from "@/sim/access";
import { parcelCapacity, scenarioMetrics } from "@/sim/capacity";
import { programmeOf } from "@/world/ops/core";
import { polyCentroid } from "@/geometry/polygon";
const w = loadWorld();
const meta: any = w.meta;
const base = new Uint8Array(fs.readFileSync("public/data/austin/landcover.bin"));
const dem = new Uint16Array(new Uint8Array(fs.readFileSync("public/data/austin/dem.bin")).buffer);
const ref = JSON.parse(fs.readFileSync("public/data/austin/reference.json", "utf8"));
let t = performance.now();
const li = prepareLandcover(w.entities.values(), w.streetGeom, w.nodeGeom, meta.grid, base);
const lc = buildLandcover(li);
console.log("landcover ms", (performance.now() - t).toFixed(0), JSON.stringify(coverStats(lc)).slice(0, 400));
t = performance.now();
const masses = li.buildings.flatMap((b) => b.masses);
const heat = runHeat(lc, { t: meta.weather.hourly.t, sw: meta.weather.hourly.sw }, { date: meta.weather.date, deltaT: 0, hours: [8, 11, 13, 15, 17, 19], lat: meta.origin.lat, lon: meta.origin.lon, utcOffset: -5, masses, trees: li.trees, blocks: ref.census.map((c: any) => ({ id: c.geoid, rings: c.poly })) });
console.log("heat ms", (performance.now() - t).toFixed(0), heat.kpi, "air", heat.airTemp, "hottest", heat.hottestBlocks.slice(0, 3));
t = performance.now();
const ro = runRunoff(lc, "25yr", []);
console.log("runoff ms", (performance.now() - t).toFixed(0), { vol: Math.round(ro.volumeM3), depth: ro.depthMm.toFixed(1), imp: ro.imperviousFraction.toFixed(3), cn: ro.weightedCN.toFixed(1) });
t = performance.now();
const fl = runFlood(lc, dem, meta.grid, meta.waterLevel + 4, meta.waterLevel, w.all("building").map((b) => ({ id: b.id, rings: b.footprint, residents: programmeOf(b).residents })));
console.log("flood ms", (performance.now() - t).toFixed(0), { area: Math.round(fl.floodedM2), bld: fl.buildings.length, res: Math.round(fl.residents) });
t = performance.now();
const origins = w.all("building").filter((b) => programmeOf(b).units > 0.5).map((b) => ({ id: b.id, p: polyCentroid(b.footprint), w: programmeOf(b).residents }));
const ai = prepareAccess(w.entities.values(), origins);
const ac = runAccess(ai);
console.log("access ms", (performance.now() - t).toFixed(0), "origins", origins.length, ac.coverage, ac.medianMinutes);
t = performance.now();
const cap = parcelCapacity(w.entities, w.all("parcel"));
console.log("capacity ms", (performance.now() - t).toFixed(0), "parcels", cap.length, "addedUnits", Math.round(cap.reduce((s, c) => s + c.addedUnits, 0)), "soft sites", cap.filter((c) => c.utilisation < 0.3 && c.addedGfa > 2000).length);
t = performance.now();
const m = scenarioMetrics(w.entities, 1.75, meta.calibration.censusPopulation);
console.log("metrics ms", (performance.now() - t).toFixed(0), Object.fromEntries(Object.entries(m).map(([k, v]) => [k, Math.round(v as number)])));
