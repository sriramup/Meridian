// npx tsx scripts/acceptance/run.ts [--only 1,2,40-45] [--report]
import fs from "node:fs";
import { runCases, type CaseResult } from "./harness";
import { A, B, C } from "./cases-abc";
import { D, E, F, G, Hc, I, J } from "./cases-dj";

const args = process.argv.slice(2);
const onlyArg = args[args.indexOf("--only") + 1];
const only = args.includes("--only")
  ? new Set(
      onlyArg.split(",").flatMap((p) => {
        const [a, b] = p.split("-").map(Number);
        return b ? Array.from({ length: b - a + 1 }, (_, k) => a + k) : [a];
      }),
    )
  : undefined;
const all = [...A, ...B, ...C, ...D, ...E, ...F, ...G, ...Hc, ...I, ...J];
// a partial run also runs the cases whose branches the selected ones build on
if (only)
  for (let grew = true; grew; ) {
    grew = false;
    for (const c of all) if (only.has(c.id)) for (const d of c.deps ?? []) if (!only.has(d)) (only.add(d), (grew = true));
  }
const t0 = performance.now();
const res = await runCases(all, only);
const n = (s: string, rs: CaseResult[] = res) => rs.filter((r) => r.status === s).length;
console.log(`\n${res.length} cases in ${((performance.now() - t0) / 1000).toFixed(0)} s — pass ${n("pass")}, partial ${n("partial")}, unsupported ${n("unsupported")}, fail ${n("fail")}`);
if (args.includes("--report")) {
  // a partial run (--only) updates its rows in the stored results; the report is rebuilt from the merged set
  let merged = res;
  if (only && fs.existsSync("docs/acceptance.json")) {
    const prev = JSON.parse(fs.readFileSync("docs/acceptance.json", "utf8")) as CaseResult[];
    if (prev.length && "prompt" in prev[0]) {
      const byId = new Map(prev.map((r) => [r.id, r]));
      for (const r of res) byId.set(r.id, r);
      merged = [...byId.values()].sort((a, b) => a.id - b.id);
    }
  }
  writeReport(merged);
}
process.exit(0);

function writeReport(rs: CaseResult[]) {
  const CAT: Record<string, string> = { A: "Buildings and architecture", B: "Streets and road geometry", C: "Transit and mobility", D: "Neighbourhood and district generation", E: "Parks, landscape, water and public space", F: "Traffic and transportation simulation", G: "Climate, heat, environment and resilience", H: "Population, zoning, land use and economics", I: "Autonomous design and optimisation", J: "Conversational, visual and contextual" };
  const icon = { pass: "✅ pass", partial: "◐ partial", unsupported: "○ unsupported", fail: "✕ fail" };
  const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
  let md = `# Acceptance suite — the 100 example prompts\n\n`;
  md += `Generated by \`npx tsx scripts/acceptance/run.ts --report\` on ${new Date().toISOString().slice(0, 10)}. Each case drives the **same tool executor the in-app agent uses** (\`src/agent/tools.ts\`) headlessly against the Austin pack, composing tools the way a planning agent would, and checks that the physical and analytical consequences happened (geometry changed, cascades resolved, models re-ran on the edited world). Simulations run in-process with the same engine as the browser worker.\n\n`;
  md += `This verifies capability, not the language model's planning: the in-app agent (Claude via \`/api/agent\`) chooses these tools itself and needs \`ANTHROPIC_API_KEY\`.\n\n`;
  md += `**${rs.length} prompts: ${n("pass", rs)} pass · ${n("partial", rs)} partial · ${n("unsupported", rs)} unsupported · ${n("fail", rs)} fail.** “Partial” means the request is executed with real geometry and models but a named piece is missing — listed explicitly, never faked.\n\n`;
  for (const c of Object.keys(CAT)) {
    const rows = rs.filter((r) => r.cat === c);
    if (!rows.length) continue;
    md += `## ${c}. ${CAT[c]}\n\n| # | Prompt | Result | Evidence (from this run) |\n|---|---|---|---|\n`;
    for (const r of rows) md += `| ${r.id} | ${esc(r.prompt)} | ${icon[r.status]} | ${esc([...r.evidence.slice(0, 4), r.gap ? `**Gap:** ${r.gap}` : "", r.error ? `**Error:** ${r.error}` : ""].filter(Boolean).join("<br>").slice(0, 900))} |\n`;
    md += `\n`;
  }
  fs.mkdirSync("docs", { recursive: true });
  fs.writeFileSync("docs/ACCEPTANCE.md", md);
  fs.writeFileSync("docs/acceptance.json", JSON.stringify(rs.map((r) => ({ ...r, ms: Math.round(r.ms) })), null, 1));
  console.log("wrote docs/ACCEPTANCE.md");
}
