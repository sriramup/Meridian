export interface PlantTreesParams {
  /** streets to line (both sides) */
  streetIds?: string[];
  /** or plant within an area polygon */
  within?: Polygon;
  spacing?: number;
  /** cap on the number of trees */
  count?: number;
  /** rank candidates by a score (higher = better) when count is set */
  score?: (p: Vec2) => number;
  canopy?: number;
  /** species id: crown and height from its mature size */
  species?: string;
}

export interface TreeCandidate {
  p: Vec2;
  streetId?: string;
}

/** candidate street-tree positions honouring sight lines, utilities, stops, existing canopy and sidewalk width */
export function streetTreeCandidates(world: World, streets: Street[], spacing = 9): { cands: TreeCandidate[]; rejected: Record<string, number> } {
  const rejected: Record<string, number> = { narrow: 0, junction: 0, utility: 0, stop: 0, existing: 0, building: 0 };
  const cands: TreeCandidate[] = [];
  for (const s of streets) {
    if (s.cls === "motorway" || s.cls === "motorway_link" || s.cls === "service") continue;
    const L = polyLength(s.path);
    const offs = stripOffsets(s.section, s.section.shift ?? 0);
    for (const side of ["left", "right"] as const) {
      const ped = side === "left" ? offs.filter((o, i) => PED_REALM.has(o.strip.type) && offs.slice(0, i).every((x) => PED_REALM.has(x.strip.type))) : offs.filter((o, i) => PED_REALM.has(o.strip.type) && offs.slice(i + 1).every((x) => PED_REALM.has(x.strip.type)));
      if (!ped.length) continue;
      const plant = ped.find((o) => o.strip.type === "planting");
      const width = ped.reduce((a, o) => a + o.strip.width, 0);
      if (!plant && width < 3.0) {
        rejected.narrow += Math.floor(L / spacing);
        continue;
      }
      // tree line: centre of planting strip, or 1.0 m behind the kerb
      const kerbSideOff = side === "left" ? ped[ped.length - 1].right : ped[0].left;
      const line = plant ? (plant.left + plant.right) / 2 : kerbSideOff + (side === "left" ? 1.0 : -1.0);
      const path = offsetPath(s.path, line);
      for (let d = 12; d < L - 12; d += spacing) {
        const p = pointAt(path, d).p;
        cands.push({ p, streetId: s.id });
      }
    }
  }
  // filters
  const out: TreeCandidate[] = [];
  for (const c of cands) {
    const p = c.p;
    const near = world.query([p[0] - 12, p[1] - 12, p[0] + 12, p[1] + 12], ["node", "tree", "utility", "stop", "building"]);
    let bad: string | null = null;
    for (const e of near) {
      if (e.kind === "node" && world.incident(e.id).length >= 3 && dist(e.p, p) < 11) bad = "junction";
      else if (e.kind === "tree" && dist((e as Tree).p, p) < 5.5) bad = "existing";
      else if (e.kind === "utility" && (e as Utility).type === "inlet" && dist((e as Utility).path[0], p) < 1.8) bad = "utility";
      else if (e.kind === "stop" && dist((e as TransitStop).p, p) < 6) bad = "stop";
      else if (e.kind === "building" && pointInPoly(p, (e as Building).footprint)) bad = "building";
      if (bad) break;
    }
    if (bad) {
      rejected[bad]++;
      continue;
    }
    if (out.some((o) => dist(o.p, p) < 5.5)) continue;
    out.push(c);
  }
  return { cands: out, rejected };
}

export function plantTrees(world: World, p: PlantTreesParams, actor: Actor, ob?: OpBuilder): OpResult {
  const b = ob ?? new OpBuilder(world, actor.author);
  let cands: TreeCandidate[] = [];
  let rejected: Record<string, number> = {};
  if (p.streetIds?.length) {
    const r = streetTreeCandidates(world, p.streetIds.map((id) => world.get<Street>(id)).filter((s): s is Street => !!s), p.spacing ?? 9);
    cands = r.cands;
    rejected = r.rejected;
  }
  if (p.within) {
    const sp = p.spacing ?? 10;
    const [x0, y0, x1, y1] = polyBBox(p.within);
    for (let x = x0; x < x1; x += sp)
      for (let y = y0; y < y1; y += sp) {
        const q: Vec2 = [x, y];
        if (!pointInPoly(q, p.within)) continue;
        if (world.query([x - 3, y - 3, x + 3, y + 3], ["building", "street"]).some((e) => (e.kind === "building" ? pointInPoly(q, (e as Building).footprint) : pointInPoly(q, streetBand(e as Street))))) continue;
        if (world.query([x - 5, y - 5, x + 5, y + 5], ["tree"]).length) continue;
        cands.push({ p: q });
      }
  }
  if (p.count && p.score) {
    const scored = cands.map((c) => ({ c, s: p.score!(c.p) })).sort((a, c) => c.s - a.s);
    cands = scored.slice(0, p.count).map((x) => x.c);
  } else if (p.count && cands.length > p.count) {
    // spread evenly over every feasible position (candidates are in street order, so a prefix would cluster)
    const n = cands.length,
      all = cands;
    cands = Array.from({ length: p.count }, (_, k) => all[Math.floor((k * n) / p.count!)]);
  }
  const sp = speciesOf(p.species);
  const r = p.canopy ?? sp?.r ?? 4.5;
  const h = sp ? sp.h * (r / sp.r) : 2.2 * r;
  for (const c of cands) b.add<Tree>({ id: newId("t"), kind: "tree", p: c.p, r, h, species: sp?.id, streetId: c.streetId, source: sp ? `Proposed street tree (${sp.name.toLowerCase()})` : "Proposed street tree", provenance: "proposed", createdBy: b.tag });
  if (!cands.length) return b.fail("No feasible tree locations (sidewalks too narrow or constrained)");
  b.summary(`Planted ${cands.length} trees (≈${fmt.m2(cands.length * Math.PI * r * r)} mature canopy)`);
  const rj = Object.entries(rejected).filter(([, v]) => v > 0);
  if (rj.length) b.summary(`Skipped candidate positions — ${rj.map(([k, v]) => `${v} ${k === "narrow" ? "sidewalk < 3 m" : k === "junction" ? "within 11 m of a junction (sight lines)" : k === "utility" ? "over a kerb inlet" : k === "stop" ? "at a bus stop" : k === "existing" ? "existing tree" : "inside a building"}`).join(", ")}`);
  b.data.treeCount = cands.length;
  if (ob) return { ok: true, report: b.report, created: [], removed: [], modified: [], data: b.data };
  return b.finish(`Plant ${cands.length} trees`);
}

export interface PlantParams {
  /** a single point, or a polyline to plant along at `spacing` */
  points: Vec2[];
  species?: string;
  spacing?: number;
}

/**
 * Hand planting: one tree per click, or a row along a drawn line. Positions inside buildings, in a
 * carriageway (between the kerbs) or on open water are skipped, as are spots within 0.6 × crown of an
 * existing or new tree (crowns may touch, trunks may not crowd).
 */
export function plantTreesAt(world: World, p: PlantParams, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  const sp = speciesOf(p.species ?? DEFAULT_SPECIES) ?? speciesOf(DEFAULT_SPECIES)!;
  const spacing = Math.max(3, p.spacing ?? sp.r * 1.8);
  const pts: Vec2[] = [];
  if (p.points.length === 1) pts.push(p.points[0]);
  else {
    const L = polyLength(p.points);
    for (let a = 0; a <= L + 1e-6; a += spacing) pts.push(pointAt(p.points, a).p);
  }
  const placed: Vec2[] = [];
  const skipped: Record<TreeProblem, number> = { outside: 0, building: 0, road: 0, water: 0, crowded: 0 };
  for (const q of pts) {
    const bad = treeProblem(world, q, sp.r, placed);
    if (bad) {
      skipped[bad]++;
      continue;
    }
    placed.push(q);
    b.add<Tree>({ id: newId("t"), kind: "tree", p: q, r: sp.r, h: sp.h, species: sp.id, source: `Planted ${sp.name.toLowerCase()}`, provenance: "proposed", createdBy: b.tag });
  }
  const why = Object.entries(skipped)
    .filter(([, v]) => v > 0)
    .map(([k, v]) => `${v} ${TREE_PROBLEM_LABEL[k as TreeProblem].toLowerCase()}`);
  if (!placed.length) return b.fail(`Nothing planted: ${why.join(", ") || "no position"}`);
  b.summary(`Planted ${placed.length} ${sp.name.toLowerCase()}${placed.length > 1 ? "s" : ""} (≈${fmt.m2(placed.length * Math.PI * sp.r * sp.r)} mature canopy)`);
  if (why.length) b.summary(`Skipped ${why.join(", ")}`);
  b.data.treeCount = placed.length;
  return b.finish(placed.length > 1 ? `Plant a row of ${placed.length} ${sp.name.toLowerCase()}s` : `Plant a ${sp.name.toLowerCase()}`);
}

/** change a tree's species (crown follows the species' mature size) or crown size */
export function updateTree(world: World, id: string, p: { species?: string; r?: number }, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  const t = b.get<Tree>(id);
  if (!t) return b.fail("Tree not found");
  const sp = speciesOf(p.species ?? t.species);
  const r = p.r ?? (p.species && sp ? sp.r : t.r);
  const h = p.species && sp ? sp.h * (r / sp.r) : t.h * (r / t.r);
  b.update<Tree>({ ...t, species: sp?.id ?? t.species, r, h });
  b.summary(`${sp ? sp.name : "Tree"}: crown ${r.toFixed(1)} m radius, ${h.toFixed(0)} m tall`);
  return b.finish(sp && p.species ? `Change tree to ${sp.name.toLowerCase()}` : "Resize tree");
}

/** give features a name (or clear it with an empty string) */
export function renameEntities(world: World, ids: string[], name: string, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  const n = name.trim();
  for (const id of ids) {
    const e = b.get(id);
    if (e && (e.kind === "street" || e.kind === "building" || e.kind === "area" || e.kind === "route" || "name" in e)) b.update({ ...e, name: n || undefined } as typeof e);
  }
  if (!ids.length) return b.fail("Nothing to rename");
  b.summary(n ? `Named “${n}”` : "Name cleared");
  return b.finish(n ? `Rename to ${n}` : "Clear name");
}

export function removeEntities(world: World, ids: string[], actor: Actor, label = "Remove"): OpResult {
  const b = new OpBuilder(world, actor.author);
  for (const id of ids) b.remove(id);
  b.summary(`${label} ${ids.length} feature${ids.length > 1 ? "s" : ""}`);
  return b.finish(`${label} ${ids.length} feature${ids.length > 1 ? "s" : ""}`);
}

