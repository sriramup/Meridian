export interface CreateAreaParams {
  type: AreaType;
  poly: Polygon;
  name?: string;
  /** retention: storage depth (m) */
  depth?: number;
  /** what to do with buildings inside: keep (carve around) or demolish */
  buildings?: "keep" | "demolish";
  /** plant shade trees on a grid (parks / plazas) */
  shadeTrees?: { spacing?: number };
}

export function createArea(world: World, p: CreateAreaParams, actor: Actor, ob?: OpBuilder): OpResult {
  const b = ob ?? new OpBuilder(world, actor.author);
  let polys: Polygon[] = [p.poly];
  // never put land uses inside open street right-of-way (unless it's a plaza replacing it)
  if (p.type !== "plaza") for (const { street } of rowConflicts(world, p.poly, { minArea: 2 })) polys = polys.flatMap((q) => difference(q, streetBand(street)));
  const displaced = { buildings: 0, gfa: 0, units: 0, parking: 0, parkingSpaces: 0, trees: 0, green: new Map<string, number>() };
  // land never becomes water by accident: other uses stop at the shoreline
  if (p.type !== "water" && p.type !== "retention")
    for (const e of world.query(polyBBox(p.poly), ["area"])) {
      const a = b.get<Area>(e.id);
      if (a && !b.isRemoved(e.id) && a.type === "water" && overlapArea(a.poly, p.poly) > 2) polys = polys.flatMap((q) => difference(q, a.poly));
    }
  const bb = polyBBox(p.poly);
  for (const e of world.query(bb, ["building"])) {
    const bld = b.get<Building>(e.id);
    if (!bld || b.isRemoved(e.id)) continue;
    const ov = overlapArea(bld.footprint, p.poly);
    if (ov < 0.25 * polyArea(bld.footprint)) {
      if (ov > 1) polys = polys.flatMap((q) => difference(q, bld.footprint));
      continue;
    }
    if ((p.buildings ?? "demolish") === "keep" || bld.historic) {
      polys = polys.flatMap((q) => difference(q, bld.footprint));
      if (bld.historic) b.summary(`Kept historic ${bld.name ?? "building"} inside the new ${p.type}`);
      continue;
    }
    const pr = programmeOf(bld);
    displaced.buildings++;
    displaced.gfa += pr.gfa;
    displaced.units += pr.units;
    b.remove(bld.id);
  }
  for (const e of world.query(bb, ["area"])) {
    const a = b.get<Area>(e.id);
    if (!a || b.isRemoved(e.id)) continue;
    const ov = overlapArea(a.poly, p.poly);
    if (ov < 2) continue;
    if (a.type === "water" && p.type !== "water" && p.type !== "retention") continue;
    if (a.type === "parking") {
      displaced.parking += ov;
      displaced.parkingSpaces += ov / 30;
    } else if (a.type !== p.type && ["park", "grass", "wood", "garden", "pitch", "playground"].includes(a.type)) displaced.green.set(a.type, (displaced.green.get(a.type) ?? 0) + ov);
    const rem = difference(a.poly, p.poly).sort((x, y) => polyArea(y) - polyArea(x))[0];
    if (rem && polyArea(rem) > 25) b.update<Area>({ ...a, poly: rem });
    else b.remove(a.id);
  }
  if (p.type === "water" || p.type === "retention") {
    for (const e of world.query(bb, ["tree"])) {
      const t = e as Tree;
      if (polys.some((q) => pointInPoly(t.p, q))) {
        b.remove(t.id);
        displaced.trees++;
      }
    }
  }
  const created: string[] = [];
  let total = 0;
  for (const q of polys) {
    if (!isValidPoly(q) || polyArea(q) < 10) continue;
    const a: Area = { id: newId("a"), kind: "area", type: p.type, poly: q, name: p.name, source: actor.author === "agent" ? "Generated by Meridian agent" : "Drawn by user", provenance: "proposed", depth: p.depth, createdBy: b.tag };
    b.add(a);
    created.push(a.id);
    total += polyArea(q);
  }
  if (!created.length) return b.fail("No usable area after removing right-of-way and existing buildings");
  const label = p.type === "retention" ? `retention pond (${fmt.m2(total)}, ${((total * (p.depth ?? 1.5)) / 1).toFixed(0)} m³ storage)` : `${p.type} (${fmt.m2(total)})`;
  b.summary(`New ${label}${p.name ? ` “${p.name}”` : ""}`);
  if (displaced.buildings) b.summary(`Displaced ${displaced.buildings} building${displaced.buildings > 1 ? "s" : ""}: −${fmt.m2(displaced.gfa)} GFA${displaced.units >= 1 ? `, −${fmt.int(displaced.units)} units` : ""}`);
  if (displaced.parking) b.summary(`Displaced ${fmt.m2(displaced.parking)} of surface parking (≈${fmt.int(displaced.parkingSpaces)} spaces at 30 m²/space)`);
  if (displaced.trees) b.summary(`${displaced.trees} trees removed for excavation`);
  for (const [t, m2] of displaced.green) b.summary(`Replaces ${fmt.m2(m2)} of existing ${t}`);
  if (p.shadeTrees && (p.type === "park" || p.type === "plaza")) {
    const sp = p.shadeTrees.spacing ?? 11;
    let n = 0;
    for (const id of created) {
      const a = b.get<Area>(id)!;
      const [x0, y0, x1, y1] = polyBBox(a.poly);
      for (let x = x0 + sp / 2; x < x1; x += sp)
        for (let y = y0 + sp / 2; y < y1; y += sp * 0.87) {
          const q: Vec2 = [x + ((Math.round(y / sp) % 2) * sp) / 2, y];
          if (!pointInPoly(q, a.poly)) continue;
          // stay off the edges
          if (closestOnPath(q, [...a.poly[0], a.poly[0][0]]).d < 3) continue;
          b.add<Tree>({ id: newId("t"), kind: "tree", p: q, r: 4.5, h: 9, source: "Proposed shade tree", provenance: "proposed", createdBy: b.tag });
          n++;
        }
    }
    if (n) b.summary(`${n} shade trees on an ${sp} m grid (mature canopy ≈ ${fmt.m2(n * Math.PI * 4.5 * 4.5)})`);
  }
  b.data.areaIds = created;
  if (ob) return { ok: true, report: b.report, created, removed: [], modified: [], data: b.data };
  return b.finish(`New ${p.type}${p.name ? ` ${p.name}` : ""}`);
}

export function convertAreas(world: World, ids: string[], type: AreaType, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  let total = 0;
  for (const id of ids) {
    const a = b.get<Area>(id);
    if (!a) continue;
    b.update<Area>({ ...a, type, provenance: "proposed", createdBy: a.createdBy ?? b.tag });
    total += polyArea(a.poly);
  }
  b.summary(`${ids.length} area${ids.length > 1 ? "s" : ""} (${fmt.m2(total)}) converted to ${type}`);
  return b.finish(`Convert to ${type}`);
}

