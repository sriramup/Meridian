function groundAt(p: Vec2): number {
  const R = rtMaybe();
  if (!R) return 150;
  const v = sampleGrid(R.meta.grid, R.dem, p);
  return Number.isFinite(v) ? v / 10 : 150;
}

function styleFor(use: Use, height: number, seed: number): Building["style"] {
  const facade: NonNullable<Building["style"]>["facade"] = height > 45 ? "glass" : use === "residential" ? (seed > 0.5 ? "masonry" : "concrete") : use === "parking" ? "concrete" : seed > 0.6 ? "metal" : "concrete";
  return { facade, tint: seed };
}

function programFor(use: Use): Partial<Record<Use, number>> {
  if (use === "mixed") return { residential: 0.82, retail: 0.12, office: 0.06 };
  return { [use]: 1 };
}

/** usable site: polygon minus street right-of-way (and optionally existing buildings) */
export function clearSite(world: World, poly: Polygon, opts: { keepBuildings?: boolean; exclude?: Set<string> } = {}): Polygon | null {
  let site: Polygon[] = [poly];
  const rows = rowConflicts(world, poly, { minArea: 0.5 });
  for (const { street } of rows) site = site.flatMap((p) => difference(p, streetBand(street)));
  // never build into water bodies
  for (const e of world.query(polyBBox(poly), ["area"])) {
    const a = e as Area;
    if (a.type === "water" && overlapArea(a.poly, poly) > 1) site = site.flatMap((p) => difference(p, bufferPoly(a.poly, 3)));
  }
  if (opts.keepBuildings) {
    for (const { building } of buildingOverlaps(world, poly, opts.exclude)) site = site.flatMap((p) => difference(p, bufferPoly(building.footprint, 2)));
  }
  const best = site.sort((a, b) => polyArea(b) - polyArea(a))[0];
  return best && isValidPoly(best) ? best : null;
}

export interface CreateBuildingParams {
  site: Polygon;
  spec: MassingSpec;
  name?: string;
  /** existing buildings to demolish (replaced by the new development) */
  replace?: string[];
  /** demolish any other building the footprint overlaps (default false → overlap is an error) */
  demolishConflicts?: boolean;
  program?: Partial<Record<Use, number>>;
  notes?: string;
  greenRoof?: boolean;
}

export function createBuilding(world: World, p: CreateBuildingParams, actor: Actor, ob?: OpBuilder): OpResult & { building?: Building } {
  const b = ob ?? new OpBuilder(world, actor.author);
  const replace = new Set(p.replace ?? []);
  const site = clearSite(world, p.site);
  if (!site) return b.fail("Site has no buildable area after removing street right-of-way");
  const gen = generateMassing(site, p.spec);
  const ground = groundAt(polyCentroid(gen.footprint));
  const seed = (Math.abs(Math.sin(polyCentroid(gen.footprint)[0] * 12.9898)) * 1000) % 1;
  const bld: Building = {
    id: newId("b"),
    kind: "building",
    footprint: gen.footprint,
    masses: gen.masses.map((m) => ({ ...m, use: m.use ?? p.spec.use })),
    height: Math.round(gen.height * 10) / 10,
    floors: gen.floors,
    use: p.spec.use,
    program: p.program ?? programFor(p.spec.use),
    name: p.name,
    ground,
    heightSource: "proposed",
    useSource: "proposed",
    source: actor.author === "agent" ? "Generated by Meridian agent" : "Drawn by user",
    createdBy: b.tag,
    notes: [p.notes, ...gen.notes].filter(Boolean).join("; ") || undefined,
    greenRoof: p.greenRoof,
    style: styleFor(p.spec.use, gen.height, seed),
  };
  const parcels = parcelsUnder(world, bld.footprint);
  if (parcels.length) bld.parcelId = parcels[0].parcel.id;
  // private circulation roads inside the site are removed by the redevelopment
  let priv = 0;
  for (const e of world.query(polyBBox(p.site), ["street"])) {
    const s = e as Street;
    if (!s.private || b.isRemoved(s.id)) continue;
    const mid = s.path[Math.floor(s.path.length / 2)];
    if (!pointInPoly(mid, p.site)) continue;
    b.remove(s.id);
    priv++;
    for (const nid of [s.from, s.to]) if (world.incident(nid).every((x) => x.id === s.id || b.isRemoved(x.id))) b.remove(nid);
  }
  if (priv) b.summary(`${priv} private driveway / parking-aisle segment${priv > 1 ? "s" : ""} removed with the site`);
  // demolitions
  for (const id of replace) {
    const old = b.get<Building>(id);
    if (!old) continue;
    if (old.historic) b.warn(`Demolishes historic-designated ${old.name ?? id}`);
    b.remove(id);
  }
  for (const { building, area } of buildingOverlaps(world, bld.footprint, replace)) {
    if (b.isRemoved(building.id)) continue;
    if (p.demolishConflicts) {
      if (building.historic) b.warn(`Demolishes historic-designated ${building.name ?? building.id}`);
      b.remove(building.id);
      b.conflict(building.id, "overlap", `Demolished ${building.name ?? "existing building"} (${fmt.area(area)} overlap)`, true);
    } else {
      // keep the existing building: carve the proposal around it
      for (const m of bld.masses) {
        const cut = difference(m.poly, bufferPoly(building.footprint, 1.5)).sort((a, c) => polyArea(c) - polyArea(a))[0];
        if (cut) m.poly = cut;
      }
      const fp = difference(bld.footprint, bufferPoly(building.footprint, 1.5)).sort((a, c) => polyArea(c) - polyArea(a))[0];
      if (fp) bld.footprint = fp;
      b.conflict(building.id, "overlap", `Kept existing ${building.name ?? "building"}; proposal carved around it`, true);
    }
  }
  bld.masses = bld.masses.filter((m) => isValidPoly(m.poly));
  if (!bld.masses.length) return b.fail("Nothing left to build after resolving conflicts");
  b.add(bld);
  // land uses under the new footprint (parking lots, lawns, parks, plazas) are cut back; trees inside are removed
  const displaced = new Map<string, number>();
  const cutter = bufferPoly(bld.footprint, 0.5);
  for (const e of world.query(polyBBox(bld.footprint), ["area"])) {
    const a = b.get<Area>(e.id);
    if (!a || b.isRemoved(e.id) || a.createdBy === b.tag) continue;
    const ov = overlapArea(a.poly, bld.footprint);
    if (ov < 2) continue;
    displaced.set(a.type, (displaced.get(a.type) ?? 0) + ov);
    const rem = difference(a.poly, cutter).filter((q) => isValidPoly(q) && polyArea(q) > 25).sort((x, y) => polyArea(y) - polyArea(x));
    if (!rem.length) b.remove(a.id);
    else {
      b.update<Area>({ ...a, poly: rem[0] });
      for (const q of rem.slice(1, 4)) b.add<Area>({ ...a, id: newId("a"), poly: q });
    }
  }
  let felled = 0;
  for (const e of world.query(polyBBox(bld.footprint), ["tree"])) {
    if (b.isRemoved(e.id) || !pointInPoly((e as Tree).p, bld.footprint)) continue;
    b.remove(e.id);
    felled++;
  }
  const prog = programmeOf(bld);
  b.summary(`New ${p.spec.typology.replace("_", " ")} — ${bld.floors} floors, ${fmt.m(bld.height)}, ${fmt.m2(prog.gfa)} GFA${prog.units >= 1 ? `, ~${fmt.int(prog.units)} units` : ""}${prog.jobs >= 1 ? `, ~${fmt.int(prog.jobs)} jobs` : ""}`);
  for (const [t, m2] of displaced) b.summary(t === "parking" ? `Displaces ${fmt.area(m2)} of surface parking (≈${fmt.int(m2 / 30)} spaces at 320 sq ft each)` : `Displaces ${fmt.area(m2)} of ${t}`);
  if (felled) b.summary(`${felled} tree${felled > 1 ? "s" : ""} inside the footprint removed`);
  if ((displaced.get("park") ?? 0) > 50) b.warn(`Builds on ${fmt.area(displaced.get("park")!)} of parkland — public park conversion typically requires a public process`);
  const removedGfa = [...replace].map((id) => world.get<Building>(id)).filter(Boolean).reduce((s, x) => s + programmeOf(x!).gfa, 0);
  if (replace.size) b.summary(`Replaces ${replace.size} existing building${replace.size > 1 ? "s" : ""} (${fmt.m2(removedGfa)})`);
  for (const iss of checkBuilding(world, bld, new Set([bld.id, ...replace]))) {
    if (iss.kind === "overlap") continue;
    (iss.severity === "error" ? b.conflict("", iss.kind, iss.message, false) : b.warn(iss.message));
  }
  b.data.buildingId = bld.id;
  b.data.gfa = prog.gfa;
  b.data.units = prog.units;
  const r = ob ? ({ ok: true, report: b.report, created: [bld.id], removed: [], modified: [] } as OpResult) : b.finish(`Build ${p.name ?? p.spec.typology.replace("_", " ")}`);
  return { ...r, building: bld };
}

export interface ModifyBuildingParams {
  ids: string[];
  height?: number;
  floors?: number;
  heightScale?: number;
  translate?: Vec2;
  rotate?: number;
  footprintScale?: number;
  use?: Use;
  program?: Partial<Record<Use, number>>;
  /** regenerate massing in place, optionally holding GFA constant */
  massing?: Partial<MassingSpec> & { typology: MassingSpec["typology"]; keepGFA?: boolean; maxHeight?: number };
  setbacks?: { aboveFloor: number; depth: number };
  greenRoof?: boolean;
  name?: string;
  /** repaint the walls (0–255 RGB); null restores the default colour. Paint only: no geometry, floor area or occupancy change */
  color?: [number, number, number] | null;
}

export function modifyBuildings(world: World, p: ModifyBuildingParams, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  let n = 0;
  for (const id of p.ids) {
    const cur = b.get<Building>(id);
    if (!cur || cur.kind !== "building") {
      b.warn(`${id} is not a building`);
      continue;
    }
    let nb: Building = { ...cur, masses: cur.masses.map((m) => ({ ...m })) };
    const before = programmeOf(cur);
    const notes: string[] = [];
    if (cur.historic && (p.massing || p.height || p.floors || p.heightScale || p.translate || p.setbacks)) b.warn(`${cur.name ?? id} is historic-designated — exterior changes need Historic Landmark Commission review`);
    if (p.massing) {
      // drop unset keys so they don't override the building's own values
      const given = Object.fromEntries(Object.entries(p.massing).filter(([k, v]) => v !== undefined && v !== null && k !== "maxHeight" && k !== "keepGFA"));
      const spec: MassingSpec = { use: p.use ?? cur.use, floors: cur.floors, ...given } as MassingSpec;
      let gen = generateMassing(cur.footprint, spec);
      if (p.massing.keepGFA && !p.massing.floors) {
        // iterate floors so the new massing holds the original floor area — within the governing height limit
        const lim = heightLimit(world, cur.footprint, cur.ground);
        if (p.massing.maxHeight != null && (lim.limit == null || p.massing.maxHeight < lim.limit)) {
          lim.limit = p.massing.maxHeight;
          lim.source.push(`study height cap ${fmtFt(p.massing.maxHeight, 0)}`);
        }
        for (let k = 0; k < 8; k++) {
          const ratio = before.gfa / Math.max(1, gen.gfa);
          if (Math.abs(ratio - 1) < 0.04) break;
          spec.floors = Math.max(2, Math.round(spec.floors * ratio));
          gen = generateMassing(cur.footprint, spec);
          if (lim.limit != null && gen.height > lim.limit + 0.5) {
            while (spec.floors > 2 && gen.height > lim.limit + 0.5) {
              spec.floors--;
              gen = generateMassing(cur.footprint, spec);
            }
            notes.push(`floor area could not be fully held: capped at ${gen.floors} floors by the ${fmtFt(lim.limit, 0)} limit (${lim.source[lim.source.length - 1]})`);
            break;
          }
        }
      }
      if (!Number.isFinite(gen.height) || !gen.masses.length) return b.fail(`Could not generate ${spec.typology} massing on ${cur.name ?? id}`);
      nb.masses = gen.masses;
      nb.footprint = gen.footprint;
      nb.height = gen.height;
      nb.floors = gen.floors;
      notes.push(...gen.notes);
    }
    if (p.height != null || p.floors != null || p.heightScale != null) {
      const target = p.height ?? (p.floors != null ? heightForFloors(p.floors, nb.use) : nb.height * (p.heightScale ?? 1));
      nb.masses = stretchAbovePodium(nb.masses, target);
      nb.height = Math.round(target * 10) / 10;
      nb.floors = p.floors ?? (p.heightScale ? Math.max(1, Math.round(nb.floors * p.heightScale)) : floorsForHeight(target, nb.use));
      notes.push(`${nb.floors - cur.floors >= 0 ? "+" : ""}${nb.floors - cur.floors} floors`);
    }
    if (p.setbacks) {
      const at = heightForFloors(p.setbacks.aboveFloor, nb.use);
      const r = addSetbacks(nb.masses, at, p.setbacks.depth);
      if (!r.changed) notes.push(`no setback applied to ${cur.name ?? id} (too low or too small)`);
      nb.masses = r.masses;
    }
    if (p.translate || p.rotate || p.footprintScale) {
      const c = polyCentroid(nb.footprint);
      const tf = (poly: Polygon) => {
        let q = poly;
        if (p.footprintScale) q = scalePoly(q, c, p.footprintScale);
        if (p.rotate) q = rotatePoly(q, c, p.rotate);
        if (p.translate) q = translatePoly(q, p.translate);
        return q;
      };
      nb.footprint = tf(nb.footprint);
      nb.masses = nb.masses.map((m) => ({ ...m, poly: tf(m.poly) }));
    }
    if (p.use) {
      nb.use = p.use;
      nb.program = p.program ?? programFor(p.use);
      nb.useSource = "proposed";
    } else if (p.program) nb.program = p.program;
    if (p.greenRoof != null) nb.greenRoof = p.greenRoof;
    if (p.name) nb.name = p.name;
    if (p.color !== undefined) {
      const { color: _old, ...rest } = cur.style ?? { facade: "concrete" as const };
      nb.style = p.color ? { ...rest, color: p.color } : cur.style ? rest : undefined;
      notes.push(p.color ? `walls repainted rgb(${p.color.join(", ")})` : "default colour restored");
    }
    if (nb.heightSource !== "proposed" && (p.height || p.floors || p.heightScale || p.massing || p.setbacks)) nb.heightSource = "proposed";
    nb = { ...nb, height: Math.max(...nb.masses.map((m) => m.top)), createdBy: nb.createdBy ?? b.tag };
    b.update(nb);
    n++;
    const after = programmeOf(nb);
    const d = after.gfa - before.gfa;
    b.summary(`${cur.name ?? "Building " + id.slice(-6)}: ${fmt.m(cur.height)} → ${fmt.m(nb.height)}, GFA ${d >= 0 ? "+" : ""}${fmt.m2(d)}${notes.length ? ` (${notes.join("; ")})` : ""}`);
    for (const iss of checkBuilding(world, nb)) (iss.severity === "error" ? b.conflict(nb.id, iss.kind, iss.message, false) : b.warn(iss.message));
  }
  if (!n) return b.fail("No buildings modified");
  return b.finish(n === 1 ? `Modify ${world.get<Building>(p.ids[0])?.name ?? "building"}` : `Modify ${n} buildings`);
}

export function removeBuildings(world: World, ids: string[], actor: Actor, reason = "Demolish"): OpResult {
  const b = new OpBuilder(world, actor.author);
  let gfa = 0,
    units = 0;
  for (const id of ids) {
    const cur = b.get<Building>(id);
    if (!cur || cur.kind !== "building") continue;
    if (cur.historic) b.warn(`${cur.name ?? id} is historic-designated — demolition requires Historic Landmark Commission approval`);
    const pr = programmeOf(cur);
    gfa += pr.gfa;
    units += pr.units;
    b.remove(id);
  }
  b.summary(`${reason} ${ids.length} building${ids.length > 1 ? "s" : ""}: −${fmt.m2(gfa)} GFA${units >= 1 ? `, −${fmt.int(units)} units` : ""}`);
  return b.finish(`${reason} ${ids.length} building${ids.length > 1 ? "s" : ""}`);
}

/** Merge several buildings into one connected development with a shared podium (and sky-bridges across streets). */
export function mergeBuildings(world: World, ids: string[], opts: { podiumFloors?: number; name?: string }, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  const blds = ids.map((id) => world.get<Building>(id)).filter((x): x is Building => !!x && x.kind === "building");
  if (blds.length < 2) return b.fail("Need at least two buildings to merge");
  const use = blds[0].use;
  const pf = opts.podiumFloors ?? 3;
  const podiumH = heightForFloors(pf, use);
  // closing operation (buffer-union-unbuffer) bridges small gaps between footprints
  const hull: Polygon = normalizePoly([convexHull(blds.flatMap((x) => x.footprint[0]))]);
  let podium: Polygon[] = [hull];
  const crossed = rowConflicts(world, hull, { minArea: 4 });
  for (const { street } of crossed) podium = podium.flatMap((p) => difference(p, streetBand(street)));
  // drop podium pieces that don't touch any merged building
  podium = podium.filter((p) => blds.some((x) => polyArea(x.footprint) > 0 && difference(x.footprint, p).reduce((s, q) => s + polyArea(q), 0) < polyArea(x.footprint) * 0.95));
  // do not swallow other buildings
  const others = new Set(ids);
  for (const p of podium.slice()) for (const { building } of buildingOverlaps(world, p, others)) podium = podium.flatMap((q) => difference(q, bufferPoly(building.footprint, 1)));
  const masses: Mass[] = [];
  for (const p of podium) if (isValidPoly(p)) masses.push({ poly: p, base: 0, top: Math.max(podiumH, 0), role: "podium" });
  for (const x of blds) for (const m of x.masses) masses.push({ ...m, role: m.top > podiumH + 1 ? (m.role === "body" ? "tower" : m.role) : m.role });
  // sky-bridges across streets that separate the pieces
  for (const { street } of crossed) {
    const band = streetBand(street);
    const inter = difference(hull, ...podium);
    const bridge = inter.filter((q) => polyArea(q) > 20 && difference(q, band).reduce((s, z) => s + polyArea(z), 0) < polyArea(q) * 0.6);
    for (const q of bridge.slice(0, 1)) {
      const slim = insetPoly(q, Math.max(0, Math.sqrt(polyArea(q)) * 0.35)) ?? q;
      masses.push({ poly: slim, base: podiumH + 2, top: podiumH + 7, role: "bridge" });
      b.summary(`Sky-bridge across ${street.name ?? "street"} (street remains open below, ${fmtFt(6.5)} clearance)`);
    }
  }
  const fp = unionMany(masses.filter((m) => m.base < 0.5).map((m) => m.poly)).sort((a, c) => polyArea(c) - polyArea(a))[0] ?? blds[0].footprint;
  const total = blds.reduce((s, x) => s + programmeOf(x).gfa, 0);
  const merged: Building = {
    ...blds[0],
    id: newId("b"),
    footprint: fp,
    masses,
    height: Math.max(...masses.map((m) => m.top)),
    floors: Math.max(...blds.map((x) => x.floors)),
    name: opts.name ?? `${blds[0].name ?? "Connected development"}`,
    heightSource: "proposed",
    useSource: blds[0].useSource,
    source: actor.author === "agent" ? "Generated by Meridian agent" : "Edited by user",
    createdBy: b.tag,
    historic: blds.some((x) => x.historic) || undefined,
    notes: `Merged from ${blds.length} buildings with a ${pf}-floor connecting podium`,
  };
  for (const x of blds) b.remove(x.id);
  b.add(merged);
  const after = programmeOf(merged);
  b.summary(`Merged ${blds.length} buildings into one development: podium ${fmt.m(podiumH)}, GFA ${fmt.m2(total)} → ${fmt.m2(after.gfa)}`);
  for (const iss of checkBuilding(world, merged, new Set([merged.id, ...ids]))) (iss.severity === "error" ? b.conflict(merged.id, iss.kind, iss.message, false) : b.warn(iss.message));
  b.data.buildingId = merged.id;
  return b.finish(`Merge ${blds.length} buildings`);
}

export function heightLimitAt(world: World, poly: Polygon) {
  return heightLimit(world, poly, groundAt(polyCentroid(poly)));
}

