/** stitch street centrelines into one oriented polyline */
export function stitch(world: World, streetIds: string[]): Vec2[] {
  const out: Vec2[] = [];
  for (const id of streetIds) {
    const s = world.get<Street>(id);
    if (!s) continue;
    let p = s.path;
    if (out.length) {
      const last = out[out.length - 1];
      if (dist(p[p.length - 1], last) < dist(p[0], last)) p = p.slice().reverse();
      out.push(...p.slice(1));
    } else {
      out.push(...p);
      if (streetIds.length > 1) {
        const nx = world.get<Street>(streetIds[1]);
        if (nx) {
          const end = p[p.length - 1];
          const d1 = Math.min(dist(end, nx.path[0]), dist(end, nx.path[nx.path.length - 1]));
          const d0 = Math.min(dist(p[0], nx.path[0]), dist(p[0], nx.path[nx.path.length - 1]));
          if (d0 < d1) out.splice(0, out.length, ...p.slice().reverse());
        }
      }
    }
  }
  return out;
}

export interface CreateRouteParams {
  mode: TransitMode;
  waypoints: Vec2[];
  name: string;
  ref?: string;
  headway?: number;
  stopSpacing?: number;
  /** convert lanes along the route to dedicated bus / tram lanes */
  dedicated?: boolean;
  color?: string;
}

export function createTransitRoute(world: World, p: CreateRouteParams, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  const net = buildNetwork(world.entities.values(), "car");
  const r = routeBetween(net, p.waypoints, "arterial");
  if (!r.streets.length) return b.fail("Could not find a street path between the waypoints");
  const path = simplifyPath(stitch(world, r.streets), 0.5);
  const L = polyLength(path);
  const spacing = p.stopSpacing ?? (p.mode === "tram" || p.mode === "brt" ? 550 : p.mode === "rapid" ? 700 : 350);
  const routeId = newId("r");
  const stops: string[] = [];
  // stops near junctions every ~spacing metres (snap to the nearest junction within 60 m)
  for (let d = 0; d <= L + 1; d += spacing) {
    const at = pointAt(path, Math.min(L, d)).p;
    let best = at,
      bd = 60;
    for (const n of r.nodes) {
      const dd = dist(n.p, at);
      if (dd < bd) {
        bd = dd;
        best = n.p;
      }
    }
    const reuse = world.query([best[0] - 25, best[1] - 25, best[0] + 25, best[1] + 25], ["stop"])[0] as TransitStop | undefined;
    if (reuse && p.mode !== "tram") {
      const cur = b.get<TransitStop>(reuse.id)!;
      b.update<TransitStop>({ ...cur, routes: [...cur.routes, routeId] });
      stops.push(reuse.id);
    } else {
      const st = b.add<TransitStop>({ id: newId("stop"), kind: "stop", p: best, name: `${p.name} stop ${stops.length + 1}`, mode: p.mode, routes: [routeId], source: "Proposed", provenance: "proposed", createdBy: b.tag });
      stops.push(st.id);
    }
  }
  const route: TransitRoute = {
    id: routeId,
    kind: "route",
    mode: p.mode,
    name: p.name,
    ref: p.ref ?? p.name.slice(0, 4).toUpperCase(),
    color: p.color ?? (p.mode === "tram" ? "#c2410c" : p.mode === "brt" ? "#b91c1c" : "#2f6fed"),
    path,
    streets: r.streets,
    stops,
    headway: p.headway ?? (p.mode === "tram" || p.mode === "brt" ? 8 : 12),
    source: actor.author === "agent" ? "Generated by Meridian agent" : "Drawn by user",
    provenance: "proposed",
    createdBy: b.tag,
  };
  b.add(route);
  b.summary(`${p.mode.toUpperCase()} route “${p.name}”: ${fmt.m(L)} on ${r.streets.length} street segments, ${stops.length} stops (~${fmt.m(spacing)} spacing), ${route.headway}-min headway`);
  if (p.dedicated) {
    // convert lanes for the whole alignment, cascading each segment
    const edit = p.mode === "tram" ? { op: "tram" as const, on: true } : { op: "bus_lanes" as const, on: true };
    let n = 0;
    for (const sid of r.streets) {
      const s = b.get<Street>(sid);
      if (!s || s.cls === "service") continue;
      const out = applySectionEdits(s.section, s.oneway, !!s.closed, [edit]);
      const ns: Street = { ...s, section: out.section, sectionSource: "proposed", createdBy: s.createdBy ?? b.tag };
      b.update(ns);
      cascadeRow(b, s, ns, "trim");
      n++;
    }
    b.summary(`${n} segments given dedicated ${p.mode === "tram" ? "tram" : "bus"} lanes (general-traffic lanes converted where ≥2 per direction, widened otherwise)`);
  }
  if (!r.ok) b.warn("Some waypoints could not be connected; route covers the reachable portion");
  b.data.routeId = routeId;
  return b.finish(`New ${p.mode} route ${p.name}`);
}

/** Re-space stops along existing routes to minimise average walking distance to residents + jobs (greedy p-median). */
export function optimizeStops(world: World, routeIds: string[], demand: { p: Vec2; w: number }[], opts: { spacingMin?: number; maxStops?: number }, actor: Actor): OpResult {
  const b = new OpBuilder(world, actor.author);
  const minSp = opts.spacingMin ?? 250;
  for (const rid of routeIds) {
    const r = world.get<TransitRoute>(rid);
    if (!r) continue;
    const L = polyLength(r.path);
    const cands: Vec2[] = [];
    for (let d = 0; d <= L; d += 40) cands.push(pointAt(r.path, d).p);
    const near = demand.filter((q) => closestOnPath(q.p, r.path).d < 600);
    const walk = (stops: Vec2[]) => {
      let s = 0,
        w = 0;
      for (const q of near) {
        let m = Infinity;
        for (const st of stops) m = Math.min(m, dist(q.p, st) * 1.3);
        s += Math.min(m, 900) * q.w;
        w += q.w;
      }
      return w ? s / w : 0;
    };
    const oldStops = r.stops.map((id) => world.get<TransitStop>(id)!).filter(Boolean);
    const before = walk(oldStops.map((s) => s.p));
    const target = opts.maxStops ?? Math.max(2, oldStops.length);
    const chosen: Vec2[] = [];
    while (chosen.length < target) {
      let best: Vec2 | null = null,
        bv = Infinity;
      for (const c of cands) {
        if (chosen.some((x) => dist(x, c) < minSp)) continue;
        const v = walk([...chosen, c]);
        if (v < bv) {
          bv = v;
          best = c;
        }
      }
      if (!best) break;
      chosen.push(best);
    }
    const after = walk(chosen);
    // replace route stops (stops shared with other routes are kept for them)
    for (const s of oldStops) {
      if (s.routes.length > 1) b.update<TransitStop>({ ...s, routes: s.routes.filter((x) => x !== rid) });
      else b.remove(s.id);
    }
    const ids: string[] = [];
    chosen
      .sort((a, c) => closestOnPath(a, r.path).along - closestOnPath(c, r.path).along)
      .forEach((p, i) => {
        const st = b.add<TransitStop>({ id: newId("stop"), kind: "stop", p, name: `${r.ref} stop ${i + 1}`, mode: r.mode, routes: [rid], source: "Optimised stop", provenance: "proposed", createdBy: b.tag });
        ids.push(st.id);
      });
    b.update<TransitRoute>({ ...r, stops: ids });
    b.summary(`Route ${r.ref}: ${oldStops.length} → ${ids.length} stops; demand-weighted walk to nearest stop ${before.toFixed(0)} → ${after.toFixed(0)} m (straight-line ×1.3 detour factor)`);
  }
  return b.finish(`Optimise stops on ${routeIds.length} route${routeIds.length > 1 ? "s" : ""}`);
}

